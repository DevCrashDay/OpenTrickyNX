#!/usr/bin/env python3
"""Stubs for the translated game, for a build check without the game.

The translated code (port/src/recomp/gen/) is made from the player's own
copy of the game and is never in the repository, so CI cannot link the real
program. This lists the symbols the host code and the runtime expect from it
-- undefined in the given objects and archives, defined nowhere among them,
and named the way the translator names things -- and writes a C file that
defines each one. Every stub function stops the program: the result links,
and shows the port builds, but does not play.

  stub_gen.py --nm aarch64-none-elf-nm --out stubs.c  host objects... archives...
"""
import argparse
import os
import re
import subprocess
import sys

# What the translator and its fix-up passes define (port/tools/fork_regen.sh).
GAME_SYMBOL = re.compile(r"^(sub_[0-9A-Fa-f]+|loc_[0-9A-Fa-f]+|xbe_entry_point|recomp_lookup"
                         r"|recomp_dispatch_init|g_last_loc|g_main_loc)$")

# The ones that are data, or return something, with their C definitions.
SPECIAL = {
    "g_last_loc": "volatile unsigned g_last_loc;",
    "g_main_loc": "volatile unsigned g_main_loc;",
    "recomp_dispatch_init": "size_t recomp_dispatch_init(void) { return 0; }",
    "recomp_lookup": "recomp_func_t recomp_lookup(uint32_t xbox_va) { (void)xbox_va; return 0; }",
}


def symbols(nm, paths):
    defined, undefined = set(), set()
    out = subprocess.run([nm, "-g", "--defined-only", *paths], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3:
            defined.add(parts[2])
    out = subprocess.run([nm, "-g", "--undefined-only", *paths], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "U":
            undefined.add(parts[1])
    return defined, undefined


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nm", default="nm")
    ap.add_argument("--out", required=True)
    ap.add_argument("inputs", nargs="+")
    args = ap.parse_args()

    defined, undefined = symbols(args.nm, args.inputs)
    wanted = sorted(s for s in undefined - defined if GAME_SYMBOL.match(s))

    lines = [
        "/* Generated by port/tools/switch/stub_gen.py: stand-ins for the translated",
        " * game, for a build check only. This program does not play. */",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "typedef void (*recomp_func_t)(void);",
        "static void stub_stop(const char *name)",
        "{",
        '    fprintf(stderr, "This build has no translated game code (%s): build it from your own '
        'copy of the game, see docs/switch.md.\\n", name);',
        "    abort();",
        "}",
    ]
    for name in wanted:
        lines.append(SPECIAL.get(name, f'void {name}(void) {{ stub_stop("{name}"); }}'))
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"stub_gen: {len(wanted)} stub(s) for the translated game", file=sys.stderr)


if __name__ == "__main__":
    main()
